package asrserver

import "testing"

func TestStripWakePhrase(t *testing.T) {
	cases := map[string]string{
		"哈罗哈罗。":                 "",
		"哈罗哈罗，我旁边有什么？":          "我旁边有什么？",
		"哈罗哈罗今天晚上我想早点睡。":        "今天晚上我想早点睡。",
		"哈喽哈喽，我旁边有什么？":          "我旁边有什么？",
		"哈啰，哈罗！你能看到我吗？":         "你能看到我吗？",
		"Hello, hello. 我旁边有什么？": "我旁边有什么？",
		"Halo halo。":            "",
		"哈ello hello.":          "", // 2026-11-15 真机：中英混写
		"hello hell喽。":          "", // 2026-11-16 真机（蓝牙麦克风）：后一遍写成「hell喽」
		"Hello hell喽.":          "",
		"Hello hell喽，现在几点了？":    "现在几点了？",
		"哈llo，我旁边有什么？":          "我旁边有什么？",
		"嗯，哈罗哈罗，我旁边有什么？":        "我旁边有什么？",       // 唤醒词前面有一两个字：一起去掉
		"我想问一下哈罗哈罗你在吗？":         "我想问一下哈罗哈罗你在吗？", // 前面字太多：不当成句首的唤醒词
		"哈喽哈喽啊。":                "",              // 2026-11-17 真机：只剩语气词也算只叫了唤醒词
		"哈罗哈罗，嗯……":              "",
		"Hello hello, um.":      "",
		"哈罗哈罗啊，今天几号？":           "啊，今天几号？", // 语气词后面还有话：照常交给模型
		"哈罗哈罗，哈哈哈":              "",
		"你能看到我吗？":               "你能看到我吗？",
		"嗯。":                    "嗯。", // 没有唤醒词：不处理（对话中间的「嗯」照常交给模型）
		"":                      "",
	}
	for in, want := range cases {
		if got := StripWakePhrase(in); got != want {
			t.Errorf("StripWakePhrase(%q) = %q，应为 %q", in, got, want)
		}
	}
}
